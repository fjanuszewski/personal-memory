/// La lista de un idioma en una tabla por idioma; vacía si no lo tiene.
#[must_use]
pub fn de_idioma(tabla: &'static [(&'static str, &'static [&'static str])], idioma: &str) -> &'static [&'static str] {
    tabla.iter().find(|(i, _)| *i == idioma).map_or(&[], |(_, lista)| lista)
}
